import core from '@bubblewrap/core';
const { TwaManifest, TwaGenerator, ConsoleLog } = core;
const out = process.argv[2];
const web = await (await fetch('http://localhost:8765/manifest.webmanifest')).json();
const m = TwaManifest.fromWebManifestJson(new URL('https://imkorea2414.github.io/manifest.webmanifest'), web);
m.packageId = 'io.github.imkorea2414.speedread';
m.host = 'imkorea2414.github.io';
m.name = '속독 트레이닝'; m.launcherName = '속독 트레이닝';
m.startUrl = '/?source=app';
m.iconUrl = 'http://localhost:8765/icons/icon-512.png';
m.maskableIconUrl = 'http://localhost:8765/icons/maskable-512.png';
m.themeColor = core.Color ? m.themeColor : m.themeColor;
m.signingKey = { path: './android.keystore', alias: 'upload' };
m.appVersionCode = 1; m.appVersionName = '1.0.0';
m.fallbackType = 'customtabs';
m.enableNotifications = false;
m.minSdkVersion = 24;
m.orientation = 'any';
m.webManifestUrl = new URL('http://localhost:8765/manifest.webmanifest');
await new TwaGenerator().createTwaProject(out, m, new ConsoleLog('gen'));
m.iconUrl = 'https://imkorea2414.github.io/icons/icon-512.png';
m.maskableIconUrl = 'https://imkorea2414.github.io/icons/maskable-512.png';
m.webManifestUrl = new URL('https://imkorea2414.github.io/manifest.webmanifest');
await m.saveToFile(out + '/twa-manifest.json');
console.log('generated', m.packageId, m.host, m.appVersionCode);
